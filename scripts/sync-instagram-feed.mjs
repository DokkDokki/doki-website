import { mkdir, readFile, readdir, rm, writeFile } from "node:fs/promises";
import path from "node:path";

const root = process.cwd();
const feedFile = path.join(root, "src/content/instagram-feed.js");
const imageDirectory = path.join(root, "public/images/instagram");
const apiVersion = process.env.INSTAGRAM_GRAPH_API_VERSION || "v22.0";
const maximumItems = 12;
const accounts = [
  { source: "doki_chibi", id: process.env.INSTAGRAM_DOKI_CHIBI_ACCOUNT_ID, token: process.env.INSTAGRAM_DOKI_CHIBI_ACCESS_TOKEN },
  { source: "doki_a6000", id: process.env.INSTAGRAM_DOKI_A6000_ACCOUNT_ID, token: process.env.INSTAGRAM_DOKI_A6000_ACCESS_TOKEN },
];

function readExistingFeed(source) {
  return readFile(feedFile, "utf8").then((contents) => JSON.parse(contents.match(/= (\[[\s\S]*\]);?\s*$/)?.[1] || "[]")).then((items) => items.filter((item) => item.source === source)).catch(() => []);
}

function imageExtension(contentType) {
  if (contentType?.includes("png")) return "png";
  if (contentType?.includes("webp")) return "webp";
  return "jpg";
}

async function fetchAccountMedia(account) {
  if (!account.id || !account.token) throw new Error(`Missing Instagram credentials for @${account.source}.`);
  const fields = "id,caption,media_type,media_url,permalink,timestamp,thumbnail_url,children{id,media_type,media_url,thumbnail_url}";
  const url = new URL(`https://graph.instagram.com/${apiVersion}/${account.id}/media`);
  url.searchParams.set("fields", fields);
  url.searchParams.set("limit", "30");
  url.searchParams.set("access_token", account.token);
  const response = await fetch(url);
  if (!response.ok) throw new Error(`Instagram returned ${response.status} for @${account.source}.`);
  const { data = [] } = await response.json();
  return data.flatMap((media) => {
    if (media.media_type === "IMAGE" && media.media_url) return [{ ...media, imageUrl: media.media_url }];
    if (media.media_type === "CAROUSEL_ALBUM") {
      const cover = media.media_url ? media : media.children?.data?.find((child) => child.media_type === "IMAGE" && child.media_url);
      return cover?.media_url ? [{ ...media, imageUrl: cover.media_url }] : [];
    }
    return [];
  });
}

async function downloadMedia(media, source) {
  const response = await fetch(media.imageUrl);
  if (!response.ok) throw new Error(`Could not download Instagram media ${media.id}.`);
  const extension = imageExtension(response.headers.get("content-type"));
  const filename = `${source}-${media.id}.${extension}`;
  await writeFile(path.join(imageDirectory, filename), Buffer.from(await response.arrayBuffer()));
  const caption = (media.caption || "").trim();
  return { id: media.id, source, permalink: media.permalink, publishedAt: media.timestamp, caption, alt: caption ? `${source}: ${caption.slice(0, 160)}` : `Instagram photo from ${source}`, imagePath: `/images/instagram/${filename}`, mediaType: media.media_type };
}

await mkdir(imageDirectory, { recursive: true });
const successfulItems = [];
const failures = [];
for (const account of accounts) {
  try {
    const media = await fetchAccountMedia(account);
    successfulItems.push(...await Promise.all(media.map((item) => downloadMedia(item, account.source))));
  } catch (error) {
    failures.push(error.message);
    successfulItems.push(...await readExistingFeed(account.source));
  }
}

if (!successfulItems.length) throw new Error(`Instagram sync did not receive usable media. ${failures.join(" ")}`);
const uniqueItems = [...new Map(successfulItems.map((item) => [item.id, item])).values()].sort((a, b) => new Date(b.publishedAt) - new Date(a.publishedAt)).slice(0, maximumItems);
const referencedFiles = new Set(uniqueItems.map((item) => path.basename(item.imagePath)));
for (const filename of await readdir(imageDirectory)) if (!referencedFiles.has(filename)) await rm(path.join(imageDirectory, filename));
await writeFile(feedFile, `// Generated by scripts/sync-instagram-feed.mjs. Do not edit manually.\nexport const instagramFeed = ${JSON.stringify(uniqueItems, null, 2)};\n`);
if (failures.length) console.warn(`Instagram sync completed with retained media: ${failures.join(" ")}`);
